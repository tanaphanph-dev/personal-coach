// เครื่องมือช่วยดึงคำอักษรแปล
export const getTranslation = (lang, path, replacements = {}) => {
  const parts = path.split('.');
  let current = translations[lang] || translations['th'];

  for (const part of parts) {
    if (current[part] === undefined) {
      // ค้นหากรณีไม่พบให้ดีดกลับไป TH
      let fallback = translations['th'];
      for (const fPart of parts) {
        if (fallback[fPart] === undefined) return path;
        fallback = fallback[fPart];
      }
      current = fallback;
      break;
    }
    current = current[part];
  }

  let text = current;
  if (typeof text === 'string') {
    Object.keys(replacements).forEach(key => {
      text = text.replace(`{{${key}}}`, replacements[key]);
    });
  }
  return text;
};
